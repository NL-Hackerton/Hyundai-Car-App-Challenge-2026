#!/usr/bin/env python3
"""SUPERSEDED (2026-11-26): the launcher icon is now design option A (design/icon/icon_final.png,
bolt + fork), shipped as PNG layers in res/mipmap-*dpi. Running this script would overwrite the
adaptive-icon XML with the old plug design - don't, unless the owner goes back to it.

Generate the StayGo adaptive launcher icon (foreground, background, monochrome).

Motif: a charging plug whose cable forks into two arrows - the dim left arrow is
"Stay" (keep charging), the bright right arrow is "Go". All geometry sits inside
the 66 dp safe zone of the 108 dp adaptive-icon canvas.

    python3 apps/staygo/tools/make_icon.py            # write res/drawable/*.xml
    python3 apps/staygo/tools/make_icon.py --svg DIR  # also write SVG previews (for review)
"""
import math
import pathlib
import sys

RES = pathlib.Path(__file__).resolve().parents[1] / "app/src/main/res"
BLUE_TOP, BLUE_BOTTOM = "#3D8BFF", "#1F5FD1"  # deck accent -> app blue (@color/blue)
STAY_ALPHA = 0.55

STROKE = 6.5
STEM_TOP = (54.0, 52.0)   # where the cable forks
STEM_BOTTOM = (54.0, 63.0)
ARM = 13.0                # arm length before the arrowhead, at 45 degrees
HEAD = 8.5                # arrowhead half-width along each side


def arrow(side):
    """Arm path from the fork + filled arrowhead path for side -1 (Stay) / +1 (Go)."""
    fx, fy = STEM_TOP
    d = ARM / math.sqrt(2)
    ex, ey = fx + side * d, fy - d                # arm end
    ux, uy = side / math.sqrt(2), -1 / math.sqrt(2)  # unit direction
    px, py = -uy, ux                              # perpendicular
    tip = (ex + ux * HEAD * 1.15, ey + uy * HEAD * 1.15)
    b1 = (ex + px * HEAD, ey + py * HEAD)
    b2 = (ex - px * HEAD, ey - py * HEAD)
    w = STROKE / 2
    # One closed arrow outline (shaft + head), so a translucent fill (Stay) has no seams.
    a1, a2 = (fx + px * w, fy + py * w), (ex + px * w, ey + py * w)
    a3, a4 = (ex - px * w, ey - py * w), (fx - px * w, fy - py * w)
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in (a1, a2, b1, tip, b2, a3, a4)) + " Z"


STEM = f"M{STEM_BOTTOM[0]},{STEM_BOTTOM[1]} L{STEM_TOP[0]},{STEM_TOP[1]}"
# Plug body (rounded rect 44..64 x 62..75, r=3.5) with two prongs below.
PLUG = ("M47.5,62 L60.5,62 Q64,62 64,65.5 L64,71.5 Q64,75 60.5,75 L47.5,75 Q44,75 44,71.5 "
        "L44,65.5 Q44,62 47.5,62 Z "
        "M48,75 L52,75 L52,82 Q52,83 51,83 L49,83 Q48,83 48,82 Z "
        "M56,75 L60,75 L60,82 Q60,83 59,83 L57,83 Q56,83 56,82 Z")

# (kind, pathData, alpha). Stay is drawn first so the opaque stem covers the fork overlap.
SHAPES = [
    ("fill", arrow(-1), STAY_ALPHA),
    ("stroke", STEM, 1.0),
    ("fill", arrow(+1), 1.0),
    ("fill", PLUG, 1.0),
]
SHIFT_Y = -4.0  # centre the glyph (y 35..83) in the 108 canvas


def vector(color="#FFFFFF"):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by apps/staygo/tools/make_icon.py; edit the script, not this file. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp"',
           '    android:viewportWidth="108" android:viewportHeight="108">',
           f'  <group android:translateY="{SHIFT_Y}">']
    for kind, d, a in SHAPES:
        if kind == "stroke":
            out.append(f'    <path android:pathData="{d}" android:strokeColor="{color}" '
                       f'android:strokeAlpha="{a}" android:strokeWidth="{STROKE}" '
                       'android:strokeLineCap="round" android:strokeLineJoin="round" />')
        else:
            out.append(f'    <path android:pathData="{d}" android:fillColor="{color}" '
                       f'android:fillAlpha="{a}" />')
    out.append('  </group>')
    out.append('</vector>')
    return "\n".join(out) + "\n"


BACKGROUND = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/staygo/tools/make_icon.py; edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear"
                android:startX="20" android:startY="0" android:endX="88" android:endY="108"
                android:startColor="{BLUE_TOP}" android:endColor="{BLUE_BOTTOM}" />
        </aapt:attr>
    </path>
</vector>
"""

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def svg(mask=None, mono=False):
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">',
             f'<defs><linearGradient id="g" x1="20" y1="0" x2="88" y2="108" gradientUnits="userSpaceOnUse">'
             f'<stop offset="0" stop-color="{BLUE_TOP}"/><stop offset="1" stop-color="{BLUE_BOTTOM}"/>'
             '</linearGradient>'
             '<clipPath id="c"><circle cx="54" cy="54" r="36"/></clipPath>'
             '<clipPath id="s"><rect x="18" y="18" width="72" height="72" rx="16"/></clipPath></defs>']
    clip = f' clip-path="url(#{mask})"' if mask else ""
    bg = "#E7ECF3" if mono else "url(#g)"
    fg = "#1D2228" if mono else "#FFFFFF"
    parts.append(f'<g{clip}><rect width="108" height="108" fill="{bg}"/><g transform="translate(0 {SHIFT_Y})">')
    for kind, d, a in SHAPES:
        if kind == "stroke":
            parts.append(f'<path d="{d}" fill="none" stroke="{fg}" stroke-opacity="{a}" '
                         f'stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"/>')
        else:
            parts.append(f'<path d="{d}" fill="{fg}" fill-opacity="{a}"/>')
    parts.append('</g></g></svg>')
    return "\n".join(parts)


def main():
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "mipmap-anydpi").mkdir(parents=True, exist_ok=True)
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector())
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector("#FFFFFF"))
    (RES / "drawable/ic_launcher_background.xml").write_text(BACKGROUND)
    for name in ("ic_launcher", "ic_launcher_round"):
        (RES / f"mipmap-anydpi/{name}.xml").write_text(ADAPTIVE)
    if "--svg" in sys.argv:
        out = pathlib.Path(sys.argv[sys.argv.index("--svg") + 1])
        out.mkdir(parents=True, exist_ok=True)
        (out / "icon_full.svg").write_text(svg())
        (out / "icon_circle.svg").write_text(svg("c"))
        (out / "icon_squircle.svg").write_text(svg("s"))
        (out / "icon_mono.svg").write_text(svg("c", mono=True))
    print("icon resources written to", RES)


if __name__ == "__main__":
    main()
